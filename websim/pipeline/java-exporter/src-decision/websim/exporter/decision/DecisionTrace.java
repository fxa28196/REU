		boolean coverageComplete = man.check("coverage.allBranchesHit", uncovered == 0,
				uncovered == 0 ? DecisionProbe.BRANCHES.length + " branches, all covered"
						: uncovered + " of " + DecisionProbe.BRANCHES.length
								+ " NOT triggered IN THIS PROCESS: " + uncoveredList);

		for (Dump.Sink s : sinks) {
			s.close();
		}
		finalSink.close();
		drawDigest.close();
		shelterSink.close();

		man.check("rows.budgetNotTripped", !DecisionProbe.budgetTripped(),
				DecisionProbe.rowsWritten() + " probe rows written (budget " + ROW_BUDGET + ")");
		man.check("size.underBudget", man.totalBytes() < 500L * 1024 * 1024,
				(man.totalBytes() / (1024 * 1024)) + " MiB on disk");

		StringBuilder extra = new StringBuilder();
		extra.append("  \"task\": \"WP8 -- Java decision-layer trace oracle\",\n");
		extra.append("  \"label\": \"").append(Dump.esc(label)).append("\",\n");
