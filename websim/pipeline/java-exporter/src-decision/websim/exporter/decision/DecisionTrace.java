		Dump.Sink coverage = man.sink("coverage", "coverage.tsv");

		header(sinks[DecisionProbe.S_HOUR],
				"per-agent per-HOUR decision rows. kind 'b' = hour bucket, 'zr' = risk update, "
				+ "'hz' = logistic hazard.");
