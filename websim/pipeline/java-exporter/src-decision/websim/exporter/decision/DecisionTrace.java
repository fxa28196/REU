/**
 * WP8 — the <b>decision-layer trace oracle</b>.
 *
 * <p>Stands up a real headless Repast runtime (a live {@link DefaultContext}, a
 * {@link Geography} projection literally named {@code "Geography"}, a
 * {@link Schedule}, a {@link RunEnvironment} parameter map and a {@link RunState}
 * master context), builds the full 6,842-resident world at the archived Phase-E
 * configurations, and steps the <b>certified</b> {@code GisAgent.step()} through
 * it, dumping every decision-layer quantity in raw IEEE-754 hex.
 *
 * <p><b>No model arithmetic is re-implemented here.</b> {@code StreetNetwork}
 * owns the graph, the snapping, the trees and the closure blocking;
 * {@code CsvLoader} owns every parse; {@code Shelter} owns capacity, reserve and
 * the open window; {@code SmokeField} owns the hourly array;
 * {@code PopulationSampler} and {@code ELayerSampler} own every build-time draw
 * and the seed derivations; {@code GisAgent} owns the whole decision layer; and
 * {@code ContextCreator$ClosureWave} owns the wave. The three step-local
 * quantities that reflection cannot reach — the hazard {@code u} and {@code p}
 * and the L1 per-candidate utility {@code v} — are read out of the certified
 * frame that computed them, through the insertion-only source probe generated by
 * {@link Instrument} (see the class doc there, and the audit file it writes).
 *
 * <p><b>What IS mirrored, and why it is safe.</b> {@code ContextCreator.build()}
 * cannot be invoked headlessly (it needs a {@code Geography.rs} scenario
 * directory, a parameter schema and a live {@code RunState} before it starts), so
 * three of its loops are mirrored statement for statement exactly as
 * {@code WorldFixtures} and {@code MovementTrace} already mirror them, with the
 * display-only side effects dropped: the shelter loop (L546-L591), the closure
 * schedule (L639-L707) and the resident placement + Phase-E second pass
 * (L710-L790). None of those loops contains a line of decision-layer arithmetic;
 * the whole of it lives in {@code GisAgent}, which is invoked, not copied. The
 * mirror is held honest by the graph census assertion, by the archived realised
 * marginals, and by the two-JVM neutrality gate.
 *
 * <p><b>Agent order is index order, not Repast's RANDOM_PRIORITY shuffle.</b>
 * Stated, not hidden. Every quantity this oracle exists to pin — {@code z_R}, the
 * hour bucket, {@code u}, {@code p}, the draw sequence, {@code awareTick},
 * {@code thetaScaled}, {@code barrierCost}, the belief set — is provably
 * order-independent: each depends only on the resident's own private stream, its
 * own attributes, and {@code anyShelterOpen(context, tick)}, which is
 * {@code static} and resident-independent. What order does change is who wins the
 * last bed, and that is already the port's single declared divergence channel
 * ({@code sim.ts:16-23}). A TypeScript run with {@code agentOrder: "identity"}
 * reproduces this dump's ordering exactly.
 */
