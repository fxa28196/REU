	private static final class Run {
		Context<Object> context;
		Geography<Object> geography;
		Schedule schedule;
		List<GisAgent> agents;
		List<Shelter> shelters;
		RecordingRandom[] rngs;
		ELayerSampler.DecisionAttributes[] das;
	}

	private static Run build(CertifiedGraph g, Cfg c, int seed, SmokeField smoke,
			List<Coordinate> campCoords, List<String> campIds, long[] campNode,
			Map<Long, StreetNetwork.ShortestPathTree> treeCache) throws Exception {
		Run w = new Run();
		w.schedule = new Schedule();
		DefaultParameters params = new DefaultParameters();
		params.addParameter("minutesPerTick", "minutesPerTick", Double.class,
				Double.valueOf(MINUTES_PER_TICK), false);
		params.addParameter("walkingSpeedMps", "walkingSpeedMps", Double.class,
				Double.valueOf(WALKING_SPEED_MPS), false);
		params.addParameter("evacuationThresholdUgM3", "evacuationThresholdUgM3", Double.class,
				Double.valueOf(EVACUATION_THRESHOLD_UGM3), false);
		params.addParameter("shelterArrivalDistanceM", "shelterArrivalDistanceM", Double.class,
				Double.valueOf(SHELTER_ARRIVAL_DISTANCE_M), false);
		RunEnvironment.init(w.schedule, null, params, true);

		w.context = new DefaultContext<Object>("DecisionTrace");
		DefaultGeography<Object> geo = new DefaultGeography<Object>("Geography");
		w.context.addProjection(geo);
		w.geography = geo;
		RunState.init();
		RunState.getInstance().setMasterContext(w.context);

		GeometryFactory fac = new GeometryFactory();

		// ---- shelters: mirror of ContextCreator.build() L546-L591 -------------
		w.shelters = new ArrayList<Shelter>();
		for (Map<String, String> r : CsvLoader.read(c.sheltersCsv)) {
			String capStr = r.get("capacity");
			Integer capacity = (capStr == null || capStr.isEmpty()) ? null : Integer.valueOf(capStr);
			boolean operating = "operating".equalsIgnoreCase(r.get("status"));
			double lon = Double.parseDouble(r.get("lon"));
			double lat = Double.parseDouble(r.get("lat"));
			Shelter shelter = new Shelter(r.get("shelter_id"), r.get("name"), capacity, operating,
					lon, lat);
			if (c.respectShelterOpeningDates == 1) {
				shelter.setOpenWindowTicks(
						tickForDate(r.get("opened"), Double.NEGATIVE_INFINITY, 0),
						tickForDate(r.get("closed"), Double.POSITIVE_INFINITY, 1));
			}
			if (capacity != null && c.triageReserveFraction > 0.0) {
				shelter.setReservedForPriority(
						(int) Math.floor(capacity.intValue() * c.triageReserveFraction));
			}
			String petCol = r.get("pet_intake");
			if (petCol != null && !petCol.trim().isEmpty()) {
				shelter.setPetIntake(Boolean.valueOf("admit".equalsIgnoreCase(petCol.trim())));
			}
			String adultsCol = r.get("adults_only");
			if (adultsCol != null && !adultsCol.trim().isEmpty()) {
				String v = adultsCol.trim();
				shelter.setAdultsOnly("1".equals(v) || "true".equalsIgnoreCase(v)
						|| "yes".equalsIgnoreCase(v));
			}
			w.context.add(shelter);
			Coordinate co = new Coordinate(lon, lat);
			w.geography.move(shelter, fac.createPoint(co));
			long nodeId = g.network.nearestNode(co);
			shelter.setGraphNodeId(nodeId);
			Long key = Long.valueOf(nodeId);
			StreetNetwork.ShortestPathTree tree = treeCache.get(key);
			if (tree == null) {
				tree = g.network.computeTree(nodeId);
				treeCache.put(key, tree);
			}
			shelter.setRouteTree(tree);
			w.shelters.add(shelter);
		}

		// ---- closures: mirror of ContextCreator.build() L639-L707 -------------
		String closuresCsv = closuresCsvFor(c.closuresCode, c.closureDraw);
		if (closuresCsv != null) {
			g.network.declareClosureSchedule();
			TreeMap<Integer, List<long[]>> waves = new TreeMap<Integer, List<long[]>>();
			for (Map<String, String> r : CsvLoader.read(closuresCsv)) {
				long a = Long.parseLong(r.get("node_a").trim());
				long b = Long.parseLong(r.get("node_b").trim());
				int hour = Integer.parseInt(r.get("activation_hour").trim());
				List<long[]> wave = waves.get(Integer.valueOf(hour));
				if (wave == null) {
					wave = new ArrayList<long[]>();
					waves.put(Integer.valueOf(hour), wave);
				}
				wave.add(new long[] { a, b });
			}
			Class<?> waveClass = Class.forName("geography.agents.ContextCreator$ClosureWave");
			Constructor<?> ctor = waveClass.getDeclaredConstructors()[0];
			ctor.setAccessible(true);
			for (Map.Entry<Integer, List<long[]>> e : waves.entrySet()) {
				int hour = e.getKey().intValue();
				Object wave = ctor.newInstance(g.network, w.shelters, e.getValue(),
						Integer.valueOf(hour));
				w.schedule.schedule(ScheduleParameters.createOneTime(hour * TICKS_PER_HOUR,
						ScheduleParameters.FIRST_PRIORITY), wave, "apply");
			}
			System.out.println("[WP8] " + closuresCsv + ": " + waves.size() + " wave(s) scheduled");
		}

		// ---- residents: mirror of ContextCreator.build() L724-L755 ------------
		Class<?> rh = Class.forName("repast.simphony.random.RandomHelper");
		rh.getMethod("init").invoke(null);
		rh.getMethod("setSeed", int.class).invoke(null, Integer.valueOf(seed));
		Method nextIntFromTo = rh.getMethod("nextIntFromTo", int.class, int.class);

		PopulationSampler sampler = c.enableHeterogeneity == 1 ? new PopulationSampler(seed) : null;
		w.agents = new ArrayList<GisAgent>(NUM_AGENTS);
		for (int i = 0; i < NUM_AGENTS; i++) {
			int idx = ((Integer) nextIntFromTo.invoke(null, Integer.valueOf(0),
					Integer.valueOf(nCamps(campCoords) - 1))).intValue();
			Coordinate coord = campCoords.get(idx);
			GisAgent agent = new GisAgent("Site " + i, g.network, campNode[idx], campIds.get(idx),
					smoke);
			agent.setStartCoord(coord.x, coord.y);
			if (sampler != null) {
				agent.setAttributes(sampler.sample());
			}
			w.context.add(agent);
			w.geography.move(agent, fac.createPoint(coord));
			w.agents.add(agent);
		}

		// ---- Phase-E second pass: mirror of ContextCreator.build() L776-L790 --
		w.rngs = new RecordingRandom[NUM_AGENTS];
		w.das = new ELayerSampler.DecisionAttributes[NUM_AGENTS];
		if (c.enableDecisionLayer != 1) {
			// Layer OFF: ContextCreator's step 11 does not run at all, so no agent
			// carries decisionConfig/decisionAttributes and step() executes the
			// pre-E path statement for statement.
			w.schedule.schedule(ScheduleParameters.createRepeating(1, 1),
					new Driver(w.agents, w.rngs), "tick");
			return w;
		}
		ELayerSampler eSampler = new ELayerSampler(seed, c.pAwareInit, c.pHeavy, c.pPet,
				c.pDependents, c.groupSpeedDeltaMps);
		GisAgent.DecisionConfig dc = new GisAgent.DecisionConfig(c.informationRegime,
				c.enableHazardDeparture, c.alphaHazard, c.bRisk, c.wOfficial, c.gammaVuln,
				c.sigmaTheta, c.riskHalfLifeH, c.lambdaOutreachPerDay, c.barrierBelongings,
				c.barrierPet, c.barrierDependents, c.petPolicyDefault == 1, c.betaTravelTime,
				c.betaCapacityPrior, c.pushThetaThreshold, c.kPush, c.pStuck, c.stuckDelayH);
		for (int i = 0; i < NUM_AGENTS; i++) {
			GisAgent a = w.agents.get(i);
			ELayerSampler.DecisionAttributes da = eSampler.sample();
			w.das[i] = da;
			DecisionProbe.beginAgent(i, a, null);
			a.setDecisionLayer(dc, da);
			DecisionProbe.endAgent();
			// Swap the certified java.util.Random for the recording SUBCLASS of it,
			// at draw 0, seeded identically: the sequence is bit-for-bit the one the
			// untraced agent would have consumed (RecordingRandom delegates to
			// super.nextDouble()).
			RecordingRandom rr = new RecordingRandom(da.decisionSeed);
			java.util.Random orig = (java.util.Random) obj(F_DECISION_RNG, a);
			if (orig == null) {
				throw new IllegalStateException("agent " + i + " has no decisionRng after arming");
			}
			F_DECISION_RNG.set(a, rr);
			w.rngs[i] = rr;
		}

		w.schedule.schedule(ScheduleParameters.createRepeating(1, 1),
				new Driver(w.agents, w.rngs), "tick");
		return w;
	}

	private static int nCamps(List<Coordinate> campCoords) {
		return campCoords.size();
	}

	// ------------------------------------------------------ end-of-run dump

	private static void dumpRun(Cfg c, int seed, String prefix, Run w, Dump.Sink finalSink,
			Dump.Sink drawDigest, Dump.Sink shelterSink) {
		for (int i = 0; i < w.agents.size(); i++) {
			GisAgent a = w.agents.get(i);
			Shelter target = a.getTargetShelter();
			Object believed = obj(F_BELIEVED, a);
			Object pushed = obj(F_PUSHED, a);
			finalSink.line(prefix + i + "\t" + a.getEncampmentId() + "\t" + a.getStartNodeId()
					+ "\t" + a.getState().name()
					+ "\t" + DecisionProbe.hx(a.getAwareTick())
					+ "\t" + DecisionProbe.hx(a.getEvacuationTick())
					+ "\t" + DecisionProbe.hx(a.getArrivalTick())
					+ "\t" + (target == null ? "" : target.getId())
					+ "\t" + DecisionProbe.hx(a.getDistanceTraveledM())
					+ "\t" + DecisionProbe.hx(a.getPlannedRouteM())
					+ "\t" + DecisionProbe.hx(a.getSnapGapM())
					+ "\t" + DecisionProbe.hx(a.getNetworkDistToShelterM())
					+ "\t" + DecisionProbe.hx(a.getExposureUgM3h())
					+ "\t" + DecisionProbe.hx(a.getVweUgM3h())
					+ "\t" + DecisionProbe.hx(a.getExposureWhileTravelingUgM3h())
					+ "\t" + DecisionProbe.hx(a.getHoursAboveUnhealthy())
					+ "\t" + DecisionProbe.hx(a.getInhaledDoseUg())
					+ "\t" + DecisionProbe.hx(a.getAirVolumeBreathedM3())
					+ "\t" + DecisionProbe.hx(a.getPeakConcUgM3())
					+ "\t" + DecisionProbe.hx(a.getOutdoorHours())
					+ "\t" + a.getRetargetCount()
					+ "\t" + a.getBlockagesEncountered()
					+ "\t" + a.getPushThroughs()
					+ "\t" + a.getReroutes()
					+ "\t" + a.getStuckEvents()
					+ "\t" + DecisionProbe.hx(a.getThetaScaled())
					+ "\t" + DecisionProbe.hx(a.getBarrierCost())
					+ "\t" + DecisionProbe.hx(dbl(F_ZR, a))
					+ "\t" + integer(F_LAST_HOUR, a)
					+ "\t" + (believed == null ? -1 : ((java.util.Set<?>) believed).size())
					+ "\t" + DecisionProbe.hx(dbl(F_STUCK_UNTIL, a))
					+ "\t" + integer(F_SEEN_VERSION, a)
					+ "\t" + lng(F_CURRENT_NODE, a)
					+ "\t" + integer(F_PATH_INDEX, a)
					+ "\t" + (pushed == null ? -1 : ((java.util.Set<?>) pushed).size())
					+ "\t" + (w.rngs[i] == null ? -1 : w.rngs[i].drawCount()));
			if (w.rngs[i] != null) {
				drawDigest.line(prefix + i + "\t" + w.das[i].decisionSeed + "\t"
						+ w.rngs[i].drawCount() + "\t" + w.rngs[i].digestHex());
			}
		}

		// Context iteration order is what the L0 tie-break (strict <) actually
		// sees, so it is recorded rather than assumed to be load order.
		Map<String, Integer> iterOrder = new LinkedHashMap<String, Integer>();
		int k = 0;
		for (Object o : w.context.getObjects(Shelter.class)) {
			iterOrder.put(((Shelter) o).getId(), Integer.valueOf(k++));
		}
		for (int i = 0; i < w.shelters.size(); i++) {
			Shelter s = w.shelters.get(i);
			Integer it = iterOrder.get(s.getId());
			shelterSink.line(prefix + i + "\t" + (it == null ? -1 : it.intValue()) + "\t"
					+ s.getId() + "\t" + (s.getCapacity() == null ? "" : s.getCapacity().toString())
					+ "\t" + (s.isOperating() ? 1 : 0)
					+ "\t" + DecisionProbe.hx(s.getOpenTick())
					+ "\t" + DecisionProbe.hx(s.getCloseTick())
					+ "\t" + s.getReservedForPriority()
					+ "\t" + (s.getPetIntake() == null ? "unrecorded"
							: (s.getPetIntake().booleanValue() ? "admit" : "refuse"))
					+ "\t" + (s.isAdultsOnly() ? 1 : 0)
					+ "\t" + s.getGraphNodeId()
					+ "\t" + s.getOccupancy() + "\t" + s.getPeakOccupancy()
					+ "\t" + s.getRefusedCount() + "\t" + s.getPolicyRefusedCount());
		}
		System.out.println(String.format(Locale.ROOT, "[WP8] %s-seed%d dumped", c.id, seed));
	}
