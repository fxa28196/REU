	/** One scheduled action per tick; steps residents in creation-index order. */
	public static final class Driver {
		private final List<GisAgent> agents;
		private final RecordingRandom[] rngs;

		Driver(List<GisAgent> agents, RecordingRandom[] rngs) {
			this.agents = agents;
			this.rngs = rngs;
		}

		/** Invoked by the Repast schedule; must stay public for the scheduler. */
		public void tick() {
			for (int i = 0; i < agents.size(); i++) {
				DecisionProbe.beginAgent(i, agents.get(i), rngs[i]);
				agents.get(i).step();
			}
			DecisionProbe.endAgent();
		}
	}

